// Writes the synthetic sample files in public/samples. Deterministic (seeded), so re-running
// produces identical files. The layout mimics real `gmx rms`, `gmx gyrate`, `gmx sasa` and
// `gmx energy` output.
import { mkdirSync, writeFileSync } from "node:fs";

const outDir = new URL("../public/samples/", import.meta.url);
mkdirSync(outDir, { recursive: true });

function mulberry32(seed) {
  return () => {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function gauss(rand) {
  return Math.sqrt(-2 * Math.log(1 - rand())) * Math.cos(2 * Math.PI * rand());
}

// AR(1) noise, so traces look like correlated MD observables rather than white noise.
function trace(rand, n, mean, sigma, phi = 0.97) {
  let e = 0;
  return Array.from({ length: n }, (_, i) => {
    e = phi * e + Math.sqrt(1 - phi * phi) * sigma * gauss(rand);
    return mean(i) + e;
  });
}

function xvg({ title, subtitle, xLabel, yLabel, legends = [], x, columns, digits = 6 }) {
  const lines = [
    "# Synthetic sample generated by XVG Studio (scripts/make-samples.mjs).",
    "# Layout mimics GROMACS analysis output; the numbers are not from a real simulation.",
    "#",
    `@    title "${title}"`,
    `@    xaxis  label "${xLabel}"`,
    `@    yaxis  label "${yLabel}"`,
    "@TYPE xy",
  ];
  if (subtitle) lines.push(`@ subtitle "${subtitle}"`);
  if (legends.length) {
    lines.push("@ view 0.15, 0.15, 0.75, 0.85", "@ legend on", "@ legend box on", "@ legend loctype view");
    lines.push("@ legend 0.78, 0.8", "@ legend length 2");
    legends.forEach((l, i) => lines.push(`@ s${i} legend "${l}"`));
  }
  for (let i = 0; i < x.length; i++) {
    lines.push(x[i].toFixed(3).padStart(12) + columns.map((c) => c[i].toFixed(digits).padStart(12)).join(""));
  }
  return lines.join("\n") + "\n";
}

const N = 2001; // 0–200 ns every 100 ps
const time = Array.from({ length: N }, (_, i) => i * 100);
const ns = (i) => (i * 100) / 1000;

const replicas = [
  { seed: 11, plateau: 0.22, tau: 8, shift: 0 },
  { seed: 22, plateau: 0.25, tau: 12, shift: 0.03 },
  { seed: 33, plateau: 0.2, tau: 6, shift: 0 },
];
replicas.forEach(({ seed, plateau, tau, shift }, r) => {
  const rand = mulberry32(seed);
  const rmsd = trace(rand, N, (i) => plateau * (1 - Math.exp(-ns(i) / tau)) + (ns(i) > 120 ? shift : 0), 0.012);
  rmsd[0] = 0;
  const y = rmsd.map((v) => Math.max(0, v));
  writeFileSync(
    new URL(`rmsd_rep${r + 1}.xvg`, outDir),
    xvg({ title: "RMSD", subtitle: "Backbone after lsq fit to Backbone", xLabel: "Time (ps)", yLabel: "RMSD (nm)", x: time, columns: [y] }),
  );
});

